"""Create the local configuration and the password hash.

The password is read from PHONEUPLOADS_NEW_PASSWORD or from a hidden prompt.
It is never written to disk in clear text and it is not passed as a program argument.
"""

from __future__ import annotations

import argparse
import getpass
import os
import re
import secrets
import sys
from pathlib import Path

from argon2 import PasswordHasher

from settings import BASE_DIR, DEFAULT_EXTENSIONS, assert_storage_allowed

HASHER = PasswordHasher(time_cost=3, memory_cost=32768, parallelism=1)
DENY = {
    "password",
    "password123",
    "123456789012",
    "qwertyuiop12",
    "changeme123",
    "admin12345",
    "letmein123",
    "parola12345",
}
KEYS = (
    "HOST",
    "PORT",
    "STORAGE_DIR",
    "MAX_UPLOAD_BYTES",
    "CHUNK_SIZE_BYTES",
    "ALLOWED_EXTENSIONS",
    "APP_USERNAME",
    "SESSION_MAX_HOURS",
    "LOGIN_MAX_ATTEMPTS",
    "LOGIN_WINDOW_SECONDS",
    "LOGIN_LOCKOUT_SECONDS",
    "COOKIE_SECURE",
    "INCOMPLETE_MAX_AGE_HOURS",
    "LOG_MAX_BYTES",
    "LOG_BACKUP_COUNT",
)


def quote(value: str) -> str:
    if '"' in value:
        raise SystemExit("Configuration values cannot contain double quotes.")
    return f'"{value}"'


def validate_password(password: str, username: str) -> None:
    if len(password) < 12:
        raise SystemExit("Password must be at least 12 characters.")
    if len(password) > 128:
        raise SystemExit("Password must be at most 128 characters.")
    if not re.search(r"[A-Za-z]", password) or not re.search(r"\d", password):
        raise SystemExit("Password must contain at least one letter and one digit.")
    folded = password.casefold()
    if folded in DENY or folded == username.casefold():
        raise SystemExit("Choose a less common password.")


def write_secret(path: Path, value: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(value + "\n", encoding="utf-8")
    os.replace(temporary, path)


def build_values(storage: Path, port: int, username: str) -> dict[str, str]:
    return {
        "HOST": "auto",
        "PORT": str(port),
        "STORAGE_DIR": str(storage),
        "MAX_UPLOAD_BYTES": str(20 * 1024 * 1024 * 1024),
        "CHUNK_SIZE_BYTES": str(4 * 1024 * 1024),
        "ALLOWED_EXTENSIONS": ",".join(DEFAULT_EXTENSIONS),
        "APP_USERNAME": username,
        "SESSION_MAX_HOURS": "168",
        "LOGIN_MAX_ATTEMPTS": "5",
        "LOGIN_WINDOW_SECONDS": "900",
        "LOGIN_LOCKOUT_SECONDS": "900",
        "COOKIE_SECURE": "false",
        "INCOMPLETE_MAX_AGE_HOURS": "168",
        "LOG_MAX_BYTES": "2000000",
        "LOG_BACKUP_COUNT": "5",
    }


def write_env(path: Path, values: dict[str, str]) -> None:
    lines = [
        "# Generated by setup_config.py.",
        "# The password hash and session secret are stored in the data folder, not here.",
    ]
    for key in KEYS:
        lines.append(f"{key}={quote(values[key])}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Configure the phone upload server.")
    parser.add_argument("--storage", required=True)
    parser.add_argument("--port", type=int, default=8787)
    parser.add_argument("--username", default="owner")
    parser.add_argument(
        "--keep-secrets",
        action="store_true",
        help="Keep the existing password hash and session secret.",
    )
    args = parser.parse_args(argv)

    if not 1024 <= args.port <= 65535:
        raise SystemExit("Port must be between 1024 and 65535.")
    username = (args.username or "owner").strip() or "owner"
    storage = assert_storage_allowed(Path(args.storage), BASE_DIR)
    storage.mkdir(parents=True, exist_ok=True)

    data_dir = BASE_DIR / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    (BASE_DIR / "logs").mkdir(parents=True, exist_ok=True)
    password_file = data_dir / "password.hash"
    secret_file = data_dir / "session.secret"

    if args.keep_secrets:
        if not password_file.is_file() or not secret_file.is_file():
            raise SystemExit("Cannot keep secrets because they have not been created yet.")
    else:
        password = os.environ.get("PHONEUPLOADS_NEW_PASSWORD")
        if password is None:
            password = getpass.getpass("Password: ")
            again = getpass.getpass("Repeat password: ")
            if password != again:
                raise SystemExit("Passwords did not match.")
        validate_password(password, username)
        write_secret(password_file, HASHER.hash(password))
        # A new password invalidates sessions that were signed with the previous secret.
        write_secret(secret_file, secrets.token_urlsafe(48))
        password = ""
        os.environ.pop("PHONEUPLOADS_NEW_PASSWORD", None)

    write_env(BASE_DIR / ".env", build_values(storage, args.port, username))
    print(f"Configuration written. Uploads will be stored in {storage}.")
    print(f"Password hash: {password_file}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except SystemExit as exc:
        if isinstance(exc.code, str):
            print(exc.code, file=sys.stderr)
            sys.exit(1)
        raise
